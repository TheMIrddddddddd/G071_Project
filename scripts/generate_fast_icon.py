"""Bake the approved fast-mode animation into a 20x16 monochrome status icon.
Uses the bundled user reference; Pillow is needed only for regeneration.
Run with --check to verify that the checked-in firmware artwork is current.
"""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts/assets/lightning_normal_to_fast.gif"
OUTPUT = ROOT / "App/ui/components/icons/app_fast_icon_data.inc"


def compact_frames():
    source, timing = [], []
    with Image.open(SOURCE) as gif:
        for frame in ImageSequence.Iterator(gif):
            source.append(frame.convert("L").point(lambda v: 255 if v >= 128 else 0))
            timing.append(frame.info.get("duration", 20))
    bounds = [frame.getbbox() for frame in source]
    box = (min(b[0] for b in bounds), min(b[1] for b in bounds),
           max(b[2] for b in bounds), max(b[3] for b in bounds))
    # Fixed crop/scale preserves the source's slight size increase on activation.
    width = round((box[2] - box[0]) * 14 / (box[3] - box[1]))
    frames = []
    for frame in source:
        small = frame.crop(box).resize((width, 14), Image.Resampling.BOX)
        small = small.point(lambda v: 255 if v >= 64 else 0)
        tile = Image.new("L", (20, 16))
        tile.paste(small, ((20 - width) // 2, 1))
        frames.append(tile)
    return frames, timing


def slash(base, amount):
    frame = base.copy()
    if amount <= 0:
        return frame
    left, top, right, bottom = base.getbbox()
    start = (max(0, left - 2), top + 1)
    end = (min(19, right + 1), bottom - 2)
    end = tuple(round(a + (b - a) * amount) for a, b in zip(start, end))
    pen = ImageDraw.Draw(frame)
    pen.line((start, end), fill=0, width=3)  # narrow clearance preserves the small outline
    pen.line((start, end), fill=255, width=1)
    return frame


def packed(frame):
    return bytes(sum((1 << bit) if (byte * 8 + bit < 20 and
                       frame.getpixel((byte * 8 + bit, row))) else 0
                     for bit in range(8))
                 for row in range(16) for byte in range(3))


def generate():
    base, timing = compact_frames()
    frames, durations = [slash(base[0], 1)], [600]
    for step in range(1, 9):
        t = step / 8
        frames.append(slash(base[0], 1 - t * t * (3 - 2 * t)))
        durations.append(40)
    frames.extend(base[1:-1]); durations.extend(max(20, t) for t in timing[1:-1])
    frames.append(base[-1]); durations.append(max(700, timing[-1]))
    frames.extend(reversed(base[:-1])); durations.extend([20] * (len(base) - 1))
    for step in range(1, 9):
        t = step / 8
        frames.append(slash(base[0], t * t * (3 - 2 * t)))
        durations.append(40)
    assert sum(durations) == 2520
    assert packed(frames[0]) == packed(frames[-1])
    unique, steps = [], []
    elapsed = 0
    for frame, duration in zip(frames, durations):
        pixels = packed(frame)
        if pixels not in unique:
            unique.append(pixels)
        index = unique.index(pixels)
        elapsed += duration
        if steps and steps[-1][1] == index:
            steps[-1] = (elapsed, index)
        else:
            steps.append((elapsed, index))
    assert len(unique) <= 255
    lines = ["// Generated by scripts/generate_fast_icon.py; do not edit by hand.",
             "// User reference SHA256: " + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
             "// XBM: 20x16, 3 bytes/row, bit 0 is left; 1-pixel OFF slash.",
             "constexpr uint8_t fast_frames[][48] = {"]
    for pixels in unique:
        lines.append("  {" + ",".join(f"0x{b:02X}" for b in pixels) + "},")
    lines.extend(["};", "struct FastStep { uint16_t end_ms; uint8_t frame; };",
                  "constexpr FastStep fast_steps[] = {"])
    lines.extend(f"  {{{end}U,{index}U}}," for end, index in steps)
    lines.extend(["};", "constexpr uint32_t fast_period_ms = 2520U;", ""])
    return "\n".join(lines), len(unique), len(steps)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, count, steps = generate()
    if args.check:
        assert OUTPUT.read_text() == text, "Regenerate fast icon data"
    else:
        OUTPUT.write_text(text)
    print(f"PASS: {count} unique 20x16 frames, {steps} timeline steps, 2520 ms")
