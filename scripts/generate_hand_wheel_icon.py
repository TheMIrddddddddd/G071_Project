"""Pack the 20x16 hand/wheel preview with a direct fingertip outline.

The bundled GIF is a 20x nearest-neighbor enlargement. Pillow is only needed
offline. --check verifies reproducibility; --verify-ui compares the fifth
status slot in test_layout's raw 128x64 page buffers with the corrected frames.
"""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts/assets/hand_wheel_clear_star.gif"
OUTPUT = ROOT / "App/app_hand_wheel_icon_data.inc"
WIDTH, HEIGHT, SCALE = 20, 16, 20
FRAME_MS = 40


def load_frames():
    frames = []
    with Image.open(SOURCE) as gif:
        assert gif.size == (WIDTH * SCALE, HEIGHT * SCALE)
        for source in ImageSequence.Iterator(gif):
            assert source.info.get("duration") == FRAME_MS
            rgb = source.convert("RGB")
            pixels = []
            for y in range(HEIGHT):
                for x in range(WIDTH):
                    # Verify every enlarged pixel is uniform; never resample or threshold.
                    block = rgb.crop((x*SCALE, y*SCALE, (x+1)*SCALE, (y+1)*SCALE))
                    colors = block.getcolors(SCALE * SCALE)
                    assert len(colors) == 1 and colors[0][1] in ((0, 0, 0), (255, 255, 255))
                    pixels.append(colors[0][1][0] != 0)
            frames.append(pixels)
    assert len(frames) == 80 and frames[0] == frames[-1]
    return correct_fingertip(frames)


def correct_fingertip(frames):
    """Replace the top halo with the finger's own cap through both transitions."""
    hand, wheel = frames[0], frames[35]
    # Local rows 0..2: one clear row, a rounded tip, then the two finger edges.
    tip = {(9, 1), (8, 2), (10, 2)}
    edits = [(x, y, (x, y) in tip) for y in range(3) for x in range(7, 12)
             if hand[y*WIDTH+x] != ((x, y) in tip)]
    bayer = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))
    result = []
    for index, original in enumerate(frames):
        ms = index * FRAME_MS
        if ms < 800 or ms >= 3000:
            t = 0.0
        elif ms < 1400:
            t = (ms - 800) / 600
        elif ms < 2400:
            t = 1.0
        else:
            t = 1 - (ms - 2400) / 600
        weight = t*t*(3-2*t)  # Same easing and fixed Bayer pattern as the reference.
        pixels = original.copy()
        for x, y, finger in edits:
            level = (1-weight)*finger + weight*wheel[y*WIDTH+x]
            pixels[y*WIDTH+x] = level > (bayer[y % 4][x % 4] + 0.5) / 16
        result.append(pixels)
    return result


def generate(frames):
    unique, sequence = [], []
    for pixels in frames:
        packed = bytes(sum(1 << bit for bit in range(8)
                           if byte*8+bit < WIDTH and pixels[y*WIDTH+byte*8+bit])
                       for y in range(HEIGHT) for byte in range(3))
        if packed not in unique:
            unique.append(packed)
        sequence.append(unique.index(packed))
    assert len(unique) <= 256
    lines = ["// Generated by scripts/generate_hand_wheel_icon.py; do not edit by hand.",
             "// Base preview SHA256: " + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
             "// Fingertip: direct rounded cap, corrected in both transition directions.",
             "// XBM: 20x16, 3 bytes/row, bit 0 is left. 7x7 equal-tip star.",
             "constexpr uint8_t hand_wheel_frames[][48] = {"]
    lines.extend("  {" + ",".join(f"0x{b:02X}" for b in frame) + "}," for frame in unique)
    lines.extend(["};", "constexpr uint8_t hand_wheel_sequence[] = {"])
    lines.extend("  " + ",".join(str(v) for v in sequence[start:start+20]) + ","
                 for start in range(0, len(sequence), 20))
    lines.extend(["};", f"constexpr uint32_t hand_wheel_frame_us = {FRAME_MS * 1000}U;", ""])
    return "\n".join(lines), len(unique)


def verify_ui(path, frames):
    raw = Path(path).read_bytes()
    assert len(raw) % 1024 == 0 and len(raw) >= len(frames) * 1024
    for index in range(len(raw) // 1024):
        fb = raw[index * 1024:(index + 1) * 1024]
        expected = frames[index % len(frames)]
        for y in range(HEIGHT):
            for x in range(WIDTH):
                actual = bool(fb[(y // 8)*128 + 84 + x] & (1 << (y % 8)))
                assert actual == expected[y*WIDTH+x], f"UI mismatch: frame {index}, pixel {x},{y}"
    print(f"PASS: {len(raw) // 1024} rendered UI frames match the corrected animation pixel-for-pixel")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--verify-ui", type=Path)
    args = parser.parse_args()
    frames = load_frames()
    text, count = generate(frames)
    if args.check:
        assert OUTPUT.read_text(encoding="utf-8") == text, "Regenerate hand/wheel icon data"
    else:
        OUTPUT.write_text(text, encoding="utf-8")
    print(f"PASS: {count} unique 20x16 frames, {len(frames)} steps, {len(frames)*FRAME_MS} ms")
    if args.verify_ui:
        verify_ui(args.verify_ui, frames)
