"""Pack the approved 20x16 charging/level GIF without changing its pixels.

Pillow is only required offline. --check checks reproducibility; --verify-ui
compares slot six of test_layout's raw OLED framebuffers with the source GIF.
"""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts/assets/battery_charge_levels_20x16.gif"
OUTPUT = ROOT / "App/ui/components/icons/app_battery_icon_data.inc"


def load_frames():
    frames, durations = [], []
    with Image.open(SOURCE) as gif:
        assert gif.size == (20, 16) and gif.info.get("loop") == 0
        for source in ImageSequence.Iterator(gif):
            rgb = source.convert("RGB")
            assert set(rgb.getdata()) <= {(0, 0, 0), (255, 255, 255)}
            frames.append([r != 0 for r, g, b in rgb.getdata()])
            durations.append(source.info.get("duration", 0))
    assert all(d > 0 and d % 40 == 0 for d in durations)
    assert sum(durations) == 6640 and frames[0] == frames[-1]
    return frames, durations


def generate(frames, durations):
    unique, steps, elapsed = [], [], 0
    for pixels, duration in zip(frames, durations):
        packed = bytes(sum(1 << bit for bit in range(8)
                           if col*8+bit < 20 and pixels[y*20+col*8+bit])
                       for y in range(16) for col in range(3))
        if packed not in unique:
            unique.append(packed)
        index = unique.index(packed)
        elapsed += duration
        if steps and steps[-1][1] == index:
            steps[-1] = (elapsed, index)
        else:
            steps.append((elapsed, index))
    assert len(unique) <= 256 and elapsed <= 65535
    lines = ["// Generated by scripts/generate_battery_icon.py; do not edit by hand.",
             "// Approved GIF SHA256: " + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
             "// XBM: 20x16, 3 bytes/row, bit 0 is left. Charging then 1/2/3/4 bars.",
             "constexpr uint8_t battery_frames[][48] = {"]
    lines.extend("  {" + ",".join(f"0x{b:02X}" for b in frame) + "}," for frame in unique)
    lines.extend(["};", "struct BatteryStep { uint16_t end_ms; uint8_t frame; };",
                  "constexpr BatteryStep battery_steps[] = {"])
    lines.extend(f"  {{{end}U,{index}U}}," for end, index in steps)
    lines.extend(["};", f"constexpr uint32_t battery_period_ms = {elapsed}U;", ""])
    return "\n".join(lines), len(unique), len(steps)


def verify_ui(path, frames, durations):
    raw = path.read_bytes()
    expected = [frame for frame, duration in zip(frames, durations)
                for _ in range(duration // 40)]
    assert len(raw) % 1024 == 0 and len(raw) >= len(expected)*1024
    for index in range(len(raw) // 1024):
        fb = raw[index*1024:(index+1)*1024]
        for y in range(16):
            for x in range(20):
                actual = bool(fb[y//8*128+105+x] & (1 << (y % 8)))
                assert actual == expected[index % len(expected)][y*20+x], \
                    f"Battery mismatch: frame {index}, pixel {x},{y}"
    print(f"PASS: {len(raw)//1024} sixth-slot UI frames match the approved battery GIF")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--verify-ui", type=Path)
    args = parser.parse_args()
    frames, durations = load_frames()
    text, count, steps = generate(frames, durations)
    if args.check:
        assert OUTPUT.read_text(encoding="utf-8") == text, "Regenerate battery icon data"
    else:
        OUTPUT.write_text(text, encoding="utf-8")
    print(f"PASS: {count} unique 20x16 frames, {steps} timeline steps, 6640 ms")
    if args.verify_ui:
        verify_ui(args.verify_ui, frames, durations)
