"""Pack the approved wide-sweep wiper GIF into a 20x16 OLED status icon.
Only offline generation requires Pillow. --check checks the generated file;
--verify-ui compares the fourth UI slot with the converted reference frames.
"""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageSequence
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/"scripts/assets/wiper_wide_sweep_128x64.gif"
OUTPUT=ROOT/"App/app_wiper_icon_data.inc"


def load_frames():
    original=[];durations=[]
    with Image.open(SOURCE) as gif:
        assert gif.size==(128,64)
        for frame in ImageSequence.Iterator(gif):
            original.append(frame.convert("L").point(lambda v:255 if v>=128 else 0))
            durations.append(frame.info.get("duration",0))
    assert sum(durations)==6400 and all(d>0 and d%40==0 for d in durations)
    boxes=[f.getbbox() for f in original]
    crop=(min(b[0] for b in boxes),min(b[1] for b in boxes),
          max(b[2] for b in boxes),max(b[3] for b in boxes))
    # One fixed crop preserves the motion origin across frames. A 20x12
    # raster uses slightly more height to distinguish the lower arc and arm.
    size=(20,12)
    frames=[]
    for frame in original:
        small=frame.crop(crop).resize(size,Image.Resampling.BOX).point(lambda v:255 if v>=64 else 0)
        tile=Image.new("L",(20,16));tile.paste(small,((20-size[0])//2,(16-size[1])//2))
        frames.append([bool(v) for v in tile.getdata()])
    return frames,durations


def generate(frames,durations):
    unique=[];steps=[];elapsed=0
    for pixels,duration in zip(frames,durations):
        data=bytes(sum(1<<bit for bit in range(8) if col*8+bit<20 and pixels[y*20+col*8+bit])
                   for y in range(16) for col in range(3))
        if data not in unique:unique.append(data)
        index=unique.index(data);elapsed+=duration
        if steps and steps[-1][1]==index:steps[-1]=(elapsed,index)
        else:steps.append((elapsed,index))
    assert len(unique)<=256 and frames[0]==frames[-1]
    lines=["// Generated by scripts/generate_wiper_icon.py; do not edit by hand.",
           "// Approved wide-sweep GIF SHA256: "+hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
           "// Fixed 20x16 tile. Source pivot (64,51), arm 35px, +/-64 degrees.",
           "// OFF 800ms, four 1200ms sweeps, OFF 800ms. XBM LSB is left.",
           "constexpr uint8_t wiper_frames[][48] = {"]
    lines.extend("  {"+",".join(f"0x{b:02X}" for b in data)+"}," for data in unique)
    lines.extend(["};","struct WiperStep { uint16_t end_ms; uint8_t frame; };",
                  "constexpr WiperStep wiper_steps[] = {"])
    lines.extend(f"  {{{end}U,{index}U}}," for end,index in steps)
    lines.extend(["};","constexpr uint32_t wiper_period_ms = 6400U;",""])
    return "\n".join(lines),len(unique),len(steps)


def verify_ui(path,frames,durations):
    raw=path.read_bytes();assert len(raw)%1024==0
    expanded=[frame for frame,duration in zip(frames,durations) for _ in range(duration//40)]
    assert len(raw)>=len(expanded)*1024
    for index in range(len(raw)//1024):
        fb=raw[index*1024:(index+1)*1024];expected=expanded[index%len(expanded)]
        for y in range(16):
            for x in range(20):
                actual=bool(fb[y//8*128+63+x]&(1<<(y%8)))
                assert actual==expected[y*20+x],f"Wiper mismatch: frame {index} at {x},{y}"
    print(f"PASS: {len(raw)//1024} fourth-slot UI frames match the converted GIF")


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    parser.add_argument("--verify-ui",type=Path)
    args=parser.parse_args();frames,durations=load_frames();text,count,steps=generate(frames,durations)
    if args.check:assert OUTPUT.read_text()==text,"Regenerate wiper icon data"
    else:OUTPUT.write_text(text)
    print(f"PASS: {count} unique 20x16 frames, {steps} timeline steps, 6400 ms")
    if args.verify_ui:verify_ui(args.verify_ui,frames,durations)
